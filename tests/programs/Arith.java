public class Arith {
    public static void main(String[] args) {
        int a = 7;
        int b = 3;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
        double x = 2.5;
        double y = 4.0;
        System.out.println(x + y);
        System.out.println(a < b);
        System.out.println(a > b);
        System.out.println(a == 7);
        System.out.println(a != b);
        boolean p = true;
        boolean q = false;
        System.out.println(p && q);
        System.out.println(p || q);
        System.out.println(!p);
        int n = -5;
        System.out.println(n);
        System.out.println(1 + 2 * 3);
    }
}
